import { createContext, useContext, useMemo, useState } from 'react';
import type { NodeId, ProgramIR } from '../ir/types';
import { wordsIn } from '../lessons/realWords';
import type { RealWord } from '../lessons/types';
import type { Teammate } from '../sim/types';
import { lineNodeIds, printProgram } from '../projection/printTs';

/** The real words the child has met so far: those of every concept whose island is open. */
export const RealWordsContext = createContext<readonly RealWord[]>([]);

/**
 * The real words for the code above: a row of pieces of code to tap, and
 * under it what a programmer calls the tapped one and how it ties to the
 * cards. One is open at a time, so the panel stays short.
 */
export function RealWords({ words, title, openFirst = false }: { words: readonly RealWord[]; title: string; openFirst?: boolean }) {
  const [picked, setPicked] = useState<string | null>(openFirst ? (words[0]?.word ?? null) : null);
  const open = words.find((w) => w.word === picked);
  if (words.length === 0) return null;
  return (
    <div className="real-words">
      <h4 className="real-words-title">{title}</h4>
      <div className="real-word-chips" role="group" aria-label={`${title}. Tap one to see what programmers call it.`}>
        {words.map((w) => (
          <button
            key={w.word}
            type="button"
            className={`real-word-chip ${w.word === picked ? 'is-open' : ''}`}
            aria-pressed={w.word === picked}
            aria-label={w.code !== undefined ? `${w.code}, ${w.word}` : w.word}
            onClick={() => setPicked(w.word === picked ? null : w.word)}
          >
            {w.code !== undefined ? <code>{w.code}</code> : w.word}
          </button>
        ))}
      </div>
      {open ? (
        <p className="real-word-text" role="status">
          <strong className="real-word-name">{open.word}</strong> {open.text}
        </p>
      ) : (
        <p className="real-word-hint">Tap one to see what programmers call it.</p>
      )}
    </div>
  );
}

/**
 * Read-only "see the code" view of the TypeScript projection. Under the
 * code sit the real words for it: in an introduction the new words of that
 * concept, anywhere else every word met so far whose code is in this program.
 */
export function CodePanel({ program, activeNodeId, team, newWords }: { program: ProgramIR; activeNodeId: NodeId | null; team?: readonly Teammate[]; newWords?: readonly RealWord[] }) {
  const source = useMemo(() => printProgram(program, team ? { team } : {}), [program, team]);
  const ids = useMemo(() => lineNodeIds(source).slice(1), [source]);
  const met = useContext(RealWordsContext);
  const words = useMemo(() => newWords ?? wordsIn(source, met), [newWords, source, met]);
  // The generated-by comment is for tooling; the child sees the import and the function.
  const lines = source.trimEnd().split('\n').filter((line) => !line.startsWith('// Generated by'));
  return (
    <section className="code-panel" aria-label="Your program as TypeScript code">
      <h3 className="code-title">The same program written in TypeScript</h3>
      <pre>
        <code>
          {lines.map((line, i) => (
            <span key={i} className={`code-line ${ids[i] && ids[i] === activeNodeId ? 'is-active' : ''}`}>
              {line.replace(/ \/\/ @node \S+$/, '')}
              {'\n'}
            </span>
          ))}
        </code>
      </pre>
      <RealWords words={words} title={newWords ? 'New real words' : 'Real words in this code'} openFirst={newWords !== undefined} />
      <p className="code-note">Every instruction is a real line of TypeScript. Later you can edit it yourself.</p>
    </section>
  );
}
